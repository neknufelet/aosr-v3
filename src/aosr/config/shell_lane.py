"""自訂房間（房間殼）高音那一路的結構設定（第五版計畫第 3 段）。

這幾格是**算法的解析度與保險絲**，不是物理常數、也不是精度契約的尺：精度契約住在
``blueprint/precision_contracts.toml``，物理量住在 ``physics_constants.toml``。每一格旁邊寫
它怎麼來的；標「未驗，推測」的是還沒量收斂就先定的值。
"""
from __future__ import annotations

from typing import Final

# 鏡像源個數的保險絲：逐面鏡射的鏡像源數大約是「面數 × (面數−1)^(階數−1)」，面多又開高階時
# 會爆量。超過就停下來說人話（請減面或降階），不讓一間房默默跑幾個鐘頭。兩百萬個在 32 面、
# 3 階的測試房（約三萬個）上留了將近七十倍的餘裕（未驗，推測：上限是記憶體量級估的，沒量時間）。
SHELL_MAX_IMAGE_SOURCES: Final[int] = 2_000_000

# 幾何判斷的長度容差（公尺）：反射點離面邊多近還算落在面裡、線段兩端離面多近不算被那個面擋。
# 取 1 微米：比匯入檢查的焊點距離（0.1 毫米）小兩個量級，又遠大於公尺級座標的雙精度捨入。
SHELL_GEOMETRY_TOL_M: Final[float] = 1e-6

# 晚期混響的分格尺寸：每個三角形沿最長邊對切，直到最長邊不超過這個長度（公尺）。
# 2026-11-27 在 6×4×3 公尺長方體（地 0.05、天花 0.8、其餘 0.02～0.3 的吸音率）量的收斂（多點積分一輪）：
# 1.0 公尺 512 格 → 1.12705；0.75 公尺 1104 格 → 1.12708；0.5 公尺 2048 格 → 1.12559；0.35 公尺 6208 格 →
# 1.12456（250 Hz 晚期能量）。1.0 與 0.75 只差十萬分之三，再細的差 0.2% 以內，所以取 1.0。
# 長方體那一路每面切 6×6 是 1.13218、每面 18×18 是 1.12755，兩路往同一個值收斂。
SHELL_PATCH_EDGE_M: Final[float] = 1.0

# 形狀因子的多點積分：每一格再對切幾輪當取樣點（1 輪＝四個子三角形的中心各一點）。
# 中心點一點對相鄰共邊或細長的格子不準（顧問三題的結論），所以至少一輪。
SHELL_FORM_FACTOR_SPLITS: Final[int] = 1
